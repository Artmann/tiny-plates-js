// Generates the code in src/generated from openapi.json.
//
//   bun run generate          regenerate from the committed spec
//   bun run generate --fetch  download the live spec first, then regenerate

import { $ } from 'bun'
import { join } from 'node:path'

const root = join(import.meta.dir, '..')
const specPath = join(root, 'openapi.json')
const generatedDirectory = join(root, 'src', 'generated')
const specUrl = 'https://api.tinyplates.dev/openapi.json'
const header = '// Generated by scripts/generate.ts from openapi.json. Do not edit.\n\n'

async function downloadSpec() {
  const response = await fetch(specUrl, { signal: AbortSignal.timeout(30_000) })

  if (!response.ok) {
    throw new Error(`Could not download the spec from ${specUrl} (status ${response.status}). Check that the API is up and try again.`)
  }

  const spec: unknown = await response.json()

  await Bun.write(specPath, `${JSON.stringify(spec, null, 2)}\n`)
  console.log(`Downloaded ${specUrl}`)
}

async function runGenerator(format: 'httpapi' | 'httpclient-type-only') {
  const result = await $`bunx openapigen --spec ${specPath} --format ${format} --name TinyPlatesApi`.cwd(root).quiet().nothrow()
  const output = result.stdout.toString()

  if (result.exitCode !== 0 || output.trim() === '') {
    throw new Error(`openapigen failed for the ${format} format:\n${result.stderr.toString()}`)
  }

  return output
}

// The type-only output also contains an Effect client. The plain client must not
// depend on effect, so keep only the schema type aliases, which are one line
// each. Multi-line aliases belong to the Effect client and are left out.
function extractTypes(source: string) {
  return source
    .split('\n')
    .filter((line) => {
      return line.startsWith('export type ') && !line.trimEnd().endsWith('{')
    })
    .join('\n')
}

if (process.argv.includes('--fetch')) {
  await downloadSpec()
}

const [api, typeOnly] = await Promise.all([
  runGenerator('httpapi'),
  runGenerator('httpclient-type-only'),
])

await Bun.write(join(generatedDirectory, 'api.ts'), header + api)
await Bun.write(join(generatedDirectory, 'types.ts'), `${header}${extractTypes(typeOnly)}\n`)

console.log('Wrote src/generated/api.ts and src/generated/types.ts')
